-- Dados basicos para o sistema funcionar (tabelas de apoio). Somente dados ficticios: nunca coloque alunos reais aqui.
-- Rodar depois de DB/estrutura.sql. Pode ser executado mais de uma vez sem duplicar.
USE [gktgym]
GO
SET IDENTITY_INSERT dbo.ALUNOS_STATUS ON;
IF NOT EXISTS (SELECT 1 FROM dbo.ALUNOS_STATUS WHERE STATUSCOD = 1) INSERT dbo.ALUNOS_STATUS (STATUSCOD, STATUSALU) VALUES (1, 'PENDENTE');
IF NOT EXISTS (SELECT 1 FROM dbo.ALUNOS_STATUS WHERE STATUSCOD = 2) INSERT dbo.ALUNOS_STATUS (STATUSCOD, STATUSALU) VALUES (2, 'PAGO');
SET IDENTITY_INSERT dbo.ALUNOS_STATUS OFF;
GO
SET IDENTITY_INSERT dbo.MODALIDADES ON;
IF NOT EXISTS (SELECT 1 FROM dbo.MODALIDADES WHERE MODALIDADECOD = 1) INSERT dbo.MODALIDADES (MODALIDADECOD, NOMEMOD) VALUES (1, N'KICKBOXING');
SET IDENTITY_INSERT dbo.MODALIDADES OFF;
GO
-- Modalidades da academia (as mesmas do formulario original, antes de as paginas lerem do banco)
INSERT dbo.MODALIDADES (NOMEMOD)
SELECT v.NOMEMOD FROM (VALUES (N'MUAY THAI'), (N'PERSONAL FIGHT'), (N'KARATÊ'), (N'KICK FEM')) v(NOMEMOD)
WHERE NOT EXISTS (SELECT 1 FROM dbo.MODALIDADES m WHERE m.NOMEMOD = v.NOMEMOD);
GO
-- Frequencia: o filtro "PLANO 2X/3X/4X" da tela de Alunos procura "2X", "3X" e "4X" neste texto
SET IDENTITY_INSERT dbo.OPCAOSEMANA ON;
IF NOT EXISTS (SELECT 1 FROM dbo.OPCAOSEMANA WHERE OPCAOCOD = 1) INSERT dbo.OPCAOSEMANA (OPCAOCOD, OPCAO) VALUES (1, N'2x por semana');
SET IDENTITY_INSERT dbo.OPCAOSEMANA OFF;
GO
-- versoes antigas deste script criavam o codigo 1 como 'Segunda', que nao combina com os filtros
UPDATE dbo.OPCAOSEMANA SET OPCAO = N'2x por semana' WHERE OPCAOCOD = 1 AND OPCAO = N'Segunda';
INSERT dbo.OPCAOSEMANA (OPCAO)
SELECT v.OPCAO FROM (VALUES (N'3x por semana'), (N'4x por semana')) v(OPCAO)
WHERE NOT EXISTS (SELECT 1 FROM dbo.OPCAOSEMANA o WHERE o.OPCAO = v.OPCAO);
GO
SET IDENTITY_INSERT dbo.PLANOS ON;
IF NOT EXISTS (SELECT 1 FROM dbo.PLANOS WHERE PLANOCOD = 1) INSERT dbo.PLANOS (PLANOCOD, PLANO) VALUES (1, N'Trimestral');
SET IDENTITY_INSERT dbo.PLANOS OFF;
GO
INSERT dbo.PLANOS (PLANO)
SELECT v.PLANO FROM (VALUES (N'Semestral'), (N'Anual')) v(PLANO)
WHERE NOT EXISTS (SELECT 1 FROM dbo.PLANOS p WHERE p.PLANO = v.PLANO);
GO
