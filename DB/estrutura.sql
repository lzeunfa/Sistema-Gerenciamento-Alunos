CREATE VIEW [dbo].[DADOSINSCRICAO] 
AS 
SELECT A.ALUMATRICULA,A.ALUNOME,M.MODALIDADECOD,P.PLANO,O.OPCAO FROM ALUNOS_INSCRICAO AI
INNER JOIN ALUNOS A ON A.ALUMATRICULA = AI.ALUNOMAT
INNER JOIN MODALIDADES M ON M.MODALIDADECOD = AI.ALUNOMOD
INNER JOIN PLANOS P ON  P.PLANOCOD = AI.ALUNOPLANO
INNER JOIN OPCAOSEMANA O ON O.OPCAOCOD = AI.ALUNOOPCAO
